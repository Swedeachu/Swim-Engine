"""Audits C/C++ (and Slang/HLSL) sources: cloc-style counts, function shape and structure smells.

usage:
  python tools/code_audit.py [roots...] [--top 25] [--long 100] [--depth 5] [--chain 4]
                             [--lambdas 3] [--save audit.json] [--compare audit.json]

Roots default to Source/. Generated files (a "generated ... do not edit" banner in the first
lines, or a path with Generated/ or .generated.) are skipped and listed as exempt.

Per file: code, comment and blank lines (cloc's rules: a line with any code is code).
Per function body (a brace block after a signature, found by a scanner that skips comments,
strings and raw strings - good enough to rank, not a parser):
  length       lines from signature to closing brace
  depth        deepest brace nesting inside the body (the body itself is 1)
  lambdas      lambda expressions defined inside
  local types  struct/class/union/enum definitions inside
  chain        longest if / else if run
  sections     responsibilities: top-level comment-separated blocks of statements, plus one
               per distinct object the body calls into at its top level beyond the first four
Each smell has a threshold; the report lists the worst offenders and how many exceed it.
--save writes everything as JSON; --compare prints the totals and per-smell counts next to an
earlier run.
"""

import argparse
import json
import os
import re
import sys

EXTENSIONS = {".cpp", ".h", ".hpp", ".c", ".cc", ".inl", ".slang", ".hlsl"}
SKIP_DIRS = {".git", "build", "out", ".cache", "node_modules", "third_party", "external", "vendor"}
GENERATED = re.compile(r"(auto-?generated|generated by).{0,80}(do not edit|don't edit)|do not edit.{0,40}generated", re.I)
CONTROL = re.compile(r"\b(if|for|while|switch|catch|else|do|return|sizeof|alignof|decltype|static_assert)\s*$")
SIGNATURE_END = re.compile(r"\)\s*(const|noexcept|override|final|mutable|volatile|&|&&|\s)*(->\s*[\w:<>,\s*&]+)?\s*$")
LOCAL_TYPE = re.compile(r"\b(struct|class|union|enum)\s+(class\s+|struct\s+)?\w*\s*(:[^;{]*)?$")
LAMBDA = re.compile(r"\]\s*(\([^()]*(\([^()]*\)[^()]*)*\))?\s*(mutable\s*)?(constexpr\s*)?(noexcept\s*)?(->\s*[\w:<>,\s*&]+)?\s*$")
CALL_TARGET = re.compile(r"\b([A-Za-z_]\w*)\s*(->|\.)\s*[A-Za-z_]\w*\s*\(")


def source_files(roots):
    for root in roots:
        if os.path.isfile(root):
            yield root
            continue
        for directory, subdirs, files in os.walk(root):
            subdirs[:] = [d for d in subdirs if d not in SKIP_DIRS]
            for name in files:
                if os.path.splitext(name)[1].lower() in EXTENSIONS:
                    yield os.path.join(directory, name)


def is_generated(path, text):
    p = path.replace("\\", "/")
    return "/Generated/" in p or ".generated." in p or bool(GENERATED.search("\n".join(text.splitlines()[:20])))


def strip(text):
    """Returns (code, kinds): code with comments and string contents blanked (newlines kept),
    and per line whether it holds code and/or comment."""
    out = []
    lines_code = set()
    lines_comment = set()
    i, n, line = 0, len(text), 0
    while i < n:
        c = text[i]
        if c == "\n":
            out.append(c)
            line += 1
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            lines_comment.add(line)
            out.append(" " * (j - i))
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            chunk = text[i:j]
            for k in range(chunk.count("\n") + 1):
                lines_comment.add(line + k)
            out.append(re.sub(r"[^\n]", " ", chunk))
            line += chunk.count("\n")
            i = j
        elif c == "R" and text.startswith('R"', i) and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")):
            m = re.match(r'R"([^(\s]{0,16})\(', text[i:])
            if not m:
                out.append(c)
                lines_code.add(line)
                i += 1
                continue
            end = text.find(")" + m.group(1) + '"', i)
            end = n if end < 0 else end + len(m.group(1)) + 2
            chunk = text[i:end]
            for k in range(chunk.count("\n") + 1):
                lines_code.add(line + k)
            out.append('""' + re.sub(r"[^\n]", " ", chunk[2:]))
            line += chunk.count("\n")
            i = end
        elif c in "\"'":
            if c == "'" and i > 0 and text[i - 1].isalnum() and i + 1 < n and text[i + 1].isalnum():
                out.append(" ")  # digit separator (1'000)
                i += 1
                continue
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            j = min(j + 1, n)
            lines_code.add(line)
            out.append(c + " " * max(j - i - 2, 0) + (c if j - i >= 2 else ""))
            i = j
        else:
            if not c.isspace():
                lines_code.add(line)
            out.append(c)
            i += 1
    return "".join(out), lines_code, lines_comment


def analyse_functions(code, raw_lines, args):
    """Brace walk over comment-free code; yields one dict per function body."""
    results = []
    stack = []  # entries: dict for functions, None for other blocks
    pending = ""  # code since the last ; { or }
    line = 0
    for idx, ch in enumerate(code):
        if ch == "\n":
            line += 1
            pending += " "
            continue
        if ch == "{":
            head = pending.strip()
            func = None
            if LAMBDA.search(head):
                for f in reversed(stack):
                    if f:
                        f["lambdas"] += 1
                        break
            elif LOCAL_TYPE.search(head) and any(stack):
                for f in reversed(stack):
                    if f:
                        f["local_types"] += 1
                        break
            elif SIGNATURE_END.search(head) and not CONTROL.search(head.split("(", 1)[0]) and "=" not in head.split("(", 1)[0] \
                    and not re.match(r"^(if|for|while|switch|catch|else)\b", head.split()[-1] if head.split() else "") and not any(stack):
                name = head.split("(", 1)[0].split()[-1] if head.split("(", 1)[0].split() else "?"
                func = {"name": name, "start": line + 1, "depth": 1, "lambdas": 0, "local_types": 0, "chain": 0, "_chain": 0,
                        "_targets": set(), "_blocks": 0, "_inblock": False, "base": len(stack)}
            stack.append(func)
            owner = next((f for f in reversed(stack) if f), None)
            if owner:
                owner["depth"] = max(owner["depth"], len(stack) - owner["base"])
            pending = ""
        elif ch == "}":
            if stack:
                closed = stack.pop()
                if closed:
                    closed["end"] = line + 1
                    closed["length"] = closed["end"] - closed["start"] + 1
                    results.append(closed)
            pending = ""
        elif ch == ";":
            owner_top = stack and stack[-1]
            if owner_top:
                for m in CALL_TARGET.finditer(pending):
                    owner_top["_targets"].add(m.group(1))
            pending = ""
        else:
            pending += ch
            continue
    # if-chains and sections from the raw text of each body
    for f in results:
        body = raw_lines[f["start"] - 1:f["end"]]
        run = best = 0
        for l in body:
            s = l.strip()
            if s.startswith("else if") or s.startswith("} else if"):
                run += 1
            elif s.startswith("if ") or s.startswith("if("):
                run = 1
            elif s and not s.startswith(("{", "}", "//", "else")) and not s.endswith((",", "&&", "||")) and run and l[:1] != " ":
                pass
            best = max(best, run)
        f["chain"] = best
        f["sections"] = section_count(body) + max(len(f["_targets"]) - 4, 0)
        for k in [k for k in f if k.startswith("_")] + ["base"]:
            f.pop(k, None)
    return results


def section_count(body):
    """Comment-separated statement groups at the body's own indentation."""
    if len(body) < 3:
        return 1
    indent = None
    for l in body[1:]:
        if l.strip() and not l.strip().startswith(("{", "}")):
            indent = len(l) - len(l.lstrip())
            break
    if indent is None:
        return 1
    sections, previous_code = 1, False
    for l in body[1:-1]:
        s = l.strip()
        here = len(l) - len(l.lstrip())
        if here != indent or not s:
            continue
        if s.startswith("//"):
            if previous_code:
                sections += 1
            previous_code = False
        else:
            previous_code = True
    return sections


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("roots", nargs="*", default=["Source"])
    parser.add_argument("--top", type=int, default=25)
    parser.add_argument("--long", type=int, default=100, help="function length threshold (lines)")
    parser.add_argument("--file", type=int, default=1000, help="file length threshold (lines)")
    parser.add_argument("--depth", type=int, default=5, help="nesting depth threshold")
    parser.add_argument("--chain", type=int, default=4, help="if/else-if chain threshold")
    parser.add_argument("--lambdas", type=int, default=3, help="lambdas-per-function threshold")
    parser.add_argument("--sections", type=int, default=6, help="responsibilities threshold")
    parser.add_argument("--save")
    parser.add_argument("--compare")
    args = parser.parse_args()

    files, functions, exempt = {}, [], []
    for path in source_files(args.roots):
        with open(path, encoding="utf-8", errors="replace") as handle:
            text = handle.read()
        key = os.path.relpath(path).replace("\\", "/")
        if is_generated(path, text):
            exempt.append(key)
            continue
        raw_lines = text.splitlines()
        code, code_lines, comment_lines = strip(text)
        total = len(raw_lines)
        n_code = sum(1 for i in range(total) if i in code_lines)
        n_comment = sum(1 for i in range(total) if i in comment_lines and i not in code_lines)
        files[key] = {"lines": total, "code": n_code, "comment": n_comment, "blank": total - n_code - n_comment}
        for f in analyse_functions(code, raw_lines, args):
            f["file"] = key
            functions.append(f)

    thresholds = {"long": ("length", args.long), "deep": ("depth", args.depth), "chains": ("chain", args.chain),
                  "lambdas": ("lambdas", args.lambdas), "local_types": ("local_types", 0), "sections": ("sections", args.sections)}
    totals = {k: sum(f[k] for f in files.values()) for k in ("lines", "code", "comment", "blank")}
    totals["files"] = len(files)
    totals["functions"] = len(functions)
    totals["big_files"] = sum(1 for f in files.values() if f["lines"] > args.file)
    smells = {name: sum(1 for f in functions if f[field] > limit) for name, (field, limit) in thresholds.items()}

    previous = None
    if args.compare:
        with open(args.compare, encoding="utf-8") as handle:
            previous = json.load(handle)

    def show(label, value, key, group):
        was = previous[group].get(key) if previous else None
        delta = "" if was is None else f"  (was {was}, {value - was:+d})"
        print(f"  {label:<34}{value:>9}{delta}")

    print(f"{len(files)} files ({len(exempt)} generated, exempt)")
    for key in ("files", "lines", "code", "comment", "blank", "functions", "big_files"):
        show(key if key != "big_files" else f"files over {args.file} lines", totals[key], key, "totals")
    print("functions over threshold:")
    for name, (field, limit) in thresholds.items():
        show(f"{field} > {limit}", smells[name], name, "smells")

    def ranked(field, title):
        worst = sorted(functions, key=lambda f: -f[field])[: args.top]
        worst = [f for f in worst if f[field] > 0]
        if worst:
            print(f"\n{title}")
            for f in worst:
                print(f"{f[field]:7d}  {f['file']}:{f['start']}  {f['name']}  (len {f['length']}, depth {f['depth']})")

    print(f"\nlargest files (code lines)")
    for key, f in sorted(files.items(), key=lambda kv: -kv[1]["code"])[: args.top]:
        print(f"{f['code']:7d}  {key}  ({f['lines']} lines, {f['comment']} comment)")
    ranked("length", "longest functions")
    ranked("depth", "deepest nesting")
    ranked("chain", "longest if/else-if chains")
    ranked("lambdas", "most lambdas defined inside")
    ranked("local_types", "local struct/class/enum definitions")
    ranked("sections", "most responsibilities (sections)")
    if exempt:
        print("\nexempt (generated): " + ", ".join(exempt[: args.top]))

    if args.save:
        with open(args.save, "w", encoding="utf-8") as handle:
            json.dump({"totals": totals, "smells": smells, "files": files, "functions": functions, "exempt": exempt}, handle, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
